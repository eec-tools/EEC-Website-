// Builds sql/social_seed.sql from src/social/seedData.js.
// Usage: node scripts/social-build-seed.js
const fs = require("fs");
const path = require("path");
const seed = require("../src/social/seedData");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

const out = [];
out.push("-- Generated by scripts/social-build-seed.js. Safe to re-run: existing rows are left alone.");
out.push("begin;");

for (const [key, value, notes] of seed.config) {
  out.push(
    `insert into social_config (key, value, notes, updated_by) values (${q(key)}, ${j(value)}, ${q(notes)}, 'seed') on conflict (key) do nothing;`
  );
}

for (const [email, name, role] of seed.members) {
  out.push(
    `insert into social_members (email, name, role) values (${q(email)}, ${q(name)}, ${q(role)}) on conflict (email) do nothing;`
  );
}

out.push("-- Writing rules: only inserted when the table is empty, so learned rules are never duplicated.");
out.push("do $$ begin if not exists (select 1 from social_preferences) then");
for (const [approver, channel, ruleType, text, status, evidence, example, updated] of seed.preferences) {
  out.push(
    `  insert into social_preferences (approver, channel, rule_type, rule_text, status, evidence_count, example, source, updated_at) values (${q(approver)}, ${q(channel)}, ${q(ruleType)}, ${q(text)}, ${q(status)}, ${evidence}, ${q(example || null)}, 'n8n li_preferences import', ${q(updated)});`
  );
}
out.push("end if; end $$;");

for (const [name, url, category, focus, active, notes] of seed.competitors) {
  out.push(
    `insert into social_competitors (name, url, category, focus, active, notes) values (${q(name)}, ${q(url || null)}, ${q(category)}, ${q(focus)}, ${active}, ${q(notes)}) on conflict (name) do nothing;`
  );
}

for (const p of seed.publishedHistory) {
  out.push(
    `insert into social_batches (batch_id, week_start, status, created_by, plan) values (${q(p.batch_id)}, ${q(p.week_start)}, 'closed', 'n8n', ${j({ note: "Imported from the n8n LinkedIn system" })}) on conflict (batch_id) do nothing;`
  );
  out.push(
    `insert into social_posts (post_id, batch_id, channel, slot_at, kind, pillar, topic, idea_key, body, status, external_url, posted_at, approved_by) values (${q(p.post_id)}, ${q(p.batch_id)}, ${q(p.channel)}, ${q(p.slot_at)}, ${q(p.kind)}, ${q(p.pillar)}, ${q(p.topic)}, ${q(p.idea_key)}, ${q("Imported from n8n. Full text is on LinkedIn: " + p.external_url)}, 'posted', ${q(p.external_url)}, ${q(p.posted_at)}, 'n8n chain (Harsh, Mohita, Shirali)') on conflict (post_id) do nothing;`
  );
}

out.push("commit;");
const file = path.join(__dirname, "..", "sql", "social_seed.sql");
fs.writeFileSync(file, out.join("\n") + "\n");
console.log(`Wrote ${file}`);
